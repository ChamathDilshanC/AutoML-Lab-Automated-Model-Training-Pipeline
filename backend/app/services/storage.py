"""Storage adapter for dataset and artifact files.

`LocalStorage` writes under a root directory. A cloud adapter (S3) implements the same protocol in
a later milestone (docs/ADR/0001). Keys are slash-separated and generated by the server.
"""

import os
import shutil
from pathlib import Path
from typing import BinaryIO, Protocol

CHUNK_BYTES = 1024 * 1024


class StorageError(Exception):
    pass


class FileTooLargeError(StorageError):
    pass


class StorageAdapter(Protocol):
    def save(self, key: str, source: BinaryIO, max_bytes: int) -> int: ...

    def read(self, key: str) -> bytes: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...

    def delete_prefix(self, prefix: str) -> None: ...


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise StorageError("Invalid storage key.")
        return path

    def save(self, key: str, source: BinaryIO, max_bytes: int) -> int:
        """Stream `source` to `key`, refusing more than `max_bytes`. Returns bytes written."""
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        partial = path.with_name(path.name + ".part")
        written = 0
        try:
            with partial.open("wb") as out:
                while chunk := source.read(CHUNK_BYTES):
                    written += len(chunk)
                    if written > max_bytes:
                        raise FileTooLargeError(f"File exceeds {max_bytes} bytes.")
                    out.write(chunk)
            os.replace(partial, path)
        except BaseException:
            partial.unlink(missing_ok=True)
            raise
        return written

    def read(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def delete_prefix(self, prefix: str) -> None:
        """Remove everything under a key prefix (a "folder"), including partial files."""
        path = self._path(prefix)
        if path == self.root:
            raise StorageError("Refusing to delete the storage root.")
        shutil.rmtree(path, ignore_errors=False) if path.is_dir() else path.unlink(missing_ok=True)
