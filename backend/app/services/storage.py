"""Storage adapters for dataset and model files.

`LocalStorage` writes under a directory; `S3Storage` uses a private S3 bucket. Both implement
`StorageAdapter`, so the rest of the system does not know which one it has (docs/ADR/0001). Keys are
slash-separated and always generated by the server, never taken from a client.
"""

import os
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, BinaryIO, Protocol

CHUNK_BYTES = 1024 * 1024
DELETE_BATCH = 1000  # the most keys S3 accepts in one delete request
MAX_KEY_LENGTH = 1024


class StorageError(Exception):
    """A storage operation failed. Messages are safe to log and never carry provider details."""


class FileTooLargeError(StorageError):
    pass


@dataclass(frozen=True)
class UploadTarget:
    """Where and how a client should send a file's bytes."""

    method: str
    url: str
    headers: dict[str, str]
    expires_in_seconds: int | None
    # True when the URL is this API (the client must send its bearer token); False for a presigned
    # storage URL, which must NOT receive the token.
    requires_auth: bool


class StorageAdapter(Protocol):
    def save(self, key: str, source: BinaryIO, max_bytes: int) -> int: ...

    def read(self, key: str) -> bytes: ...

    def size(self, key: str) -> int:
        """Size in bytes of a stored file. Raises `FileNotFoundError` if there is none."""
        ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...

    def delete_prefix(self, prefix: str) -> None: ...

    def upload_target(self, key: str, size_bytes: int, content_type: str) -> UploadTarget | None:
        """A target for direct client uploads, or `None` if the client should upload to the API."""
        ...


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise StorageError("Invalid storage key.")
        return path

    def save(self, key: str, source: BinaryIO, max_bytes: int) -> int:
        """Stream `source` to `key`, refusing more than `max_bytes`. Returns bytes written."""
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        partial = path.with_name(path.name + ".part")
        written = 0
        try:
            with partial.open("wb") as out:
                while chunk := source.read(CHUNK_BYTES):
                    written += len(chunk)
                    if written > max_bytes:
                        raise FileTooLargeError(f"File exceeds {max_bytes} bytes.")
                    out.write(chunk)
            os.replace(partial, path)
        except BaseException:
            partial.unlink(missing_ok=True)
            raise
        return written

    def read(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def delete_prefix(self, prefix: str) -> None:
        """Remove everything under a key prefix (a "folder"), including partial files."""
        path = self._path(prefix)
        if path == self.root:
            raise StorageError("Refusing to delete the storage root.")
        if path.is_dir():
            shutil.rmtree(path)
        else:
            path.unlink(missing_ok=True)

    def upload_target(self, key: str, size_bytes: int, content_type: str) -> UploadTarget | None:
        return None


def _is_missing(error: Exception) -> bool:
    response = getattr(error, "response", None) or {}
    return str(response.get("Error", {}).get("Code")) in {"404", "NoSuchKey", "NotFound"}


class S3Storage:
    """Objects in one private S3 bucket.

    Credentials come from the standard AWS chain (environment, shared config, instance or task
    role); nothing is configured here. Every failure is reported as a `StorageError` with a fixed
    message, so provider error text (which can contain bucket and key names) never reaches a
    caller or a user.
    """

    def __init__(self, client: Any, bucket: str, presign_expires_seconds: int = 300) -> None:
        self._client = client
        self._bucket = bucket
        self._expires = presign_expires_seconds

    @staticmethod
    def _check(key: str) -> str:
        parts = key.split("/")
        if not key or key.startswith("/") or "\\" in key or ".." in parts or "" in parts:
            raise StorageError("Invalid storage key.")
        if len(key.encode()) > MAX_KEY_LENGTH:
            raise StorageError("Invalid storage key.")
        return key

    def save(self, key: str, source: BinaryIO, max_bytes: int) -> int:
        self._check(key)
        written = 0
        with tempfile.SpooledTemporaryFile(max_size=8 * CHUNK_BYTES) as spool:
            while chunk := source.read(CHUNK_BYTES):
                written += len(chunk)
                if written > max_bytes:
                    raise FileTooLargeError(f"File exceeds {max_bytes} bytes.")
                spool.write(chunk)
            spool.seek(0)
            try:
                self._client.upload_fileobj(spool, self._bucket, key)
            except Exception as exc:
                raise StorageError("Could not write to object storage.") from exc
        return written

    def read(self, key: str) -> bytes:
        self._check(key)
        try:
            body = self._client.get_object(Bucket=self._bucket, Key=key)["Body"]
            return bytes(body.read())
        except Exception as exc:
            if _is_missing(exc):
                raise FileNotFoundError(key) from None
            raise StorageError("Could not read from object storage.") from exc

    def size(self, key: str) -> int:
        self._check(key)
        try:
            return int(self._client.head_object(Bucket=self._bucket, Key=key)["ContentLength"])
        except Exception as exc:
            if _is_missing(exc):
                raise FileNotFoundError(key) from None
            raise StorageError("Could not read from object storage.") from exc

    def exists(self, key: str) -> bool:
        try:
            self.size(key)
        except FileNotFoundError:
            return False
        return True

    def delete(self, key: str) -> None:
        self._check(key)
        try:
            self._client.delete_object(Bucket=self._bucket, Key=key)  # no error if already gone
        except Exception as exc:
            raise StorageError("Could not delete from object storage.") from exc

    def delete_prefix(self, prefix: str) -> None:
        """Delete every object under `prefix/`.

        The trailing slash matters: S3 matches prefixes as plain text, so `models/md_1` would also
        match `models/md_10/...`.
        """
        self._check(prefix.rstrip("/"))
        folder = prefix.rstrip("/") + "/"
        try:
            batch: list[dict[str, str]] = []
            pages = self._client.get_paginator("list_objects_v2").paginate(
                Bucket=self._bucket, Prefix=folder
            )
            for page in pages:
                for item in page.get("Contents", []):
                    batch.append({"Key": item["Key"]})
                    if len(batch) == DELETE_BATCH:
                        self._delete_batch(batch)
                        batch = []
            if batch:
                self._delete_batch(batch)
        except StorageError:
            raise
        except Exception as exc:
            raise StorageError("Could not delete from object storage.") from exc

    def _delete_batch(self, batch: list[dict[str, str]]) -> None:
        result = self._client.delete_objects(
            Bucket=self._bucket, Delete={"Objects": batch, "Quiet": True}
        )
        if result.get("Errors"):
            raise StorageError("Could not delete some objects from object storage.")

    def upload_target(self, key: str, size_bytes: int, content_type: str) -> UploadTarget | None:
        """A short-lived presigned PUT URL for this one key.

        The content type and exact length are part of the signature, so storage itself rejects an
        upload of a different size or type.
        """
        self._check(key)
        try:
            url = self._client.generate_presigned_url(
                "put_object",
                Params={
                    "Bucket": self._bucket,
                    "Key": key,
                    "ContentType": content_type,
                    "ContentLength": size_bytes,
                },
                ExpiresIn=self._expires,
                HttpMethod="PUT",
            )
        except Exception as exc:
            raise StorageError("Could not create an upload URL.") from exc
        return UploadTarget(
            method="PUT",
            url=url,
            headers={"Content-Type": content_type},
            expires_in_seconds=self._expires,
            requires_auth=False,
        )
